val appVersionName: String = rootProject.extra["appVersionName"] as String

// Generated constant so common code (User-Agent) knows the app version without Android's BuildConfig.
val genBuildInfo = tasks.register("generateBuildInfo") {
    val out = layout.buildDirectory.dir("generated/buildinfo/kotlin")
    inputs.property("version", appVersionName)
    outputs.dir(out)
    doLast {
        val f = out.get().file("com/jayant/spendsense/BuildInfo.kt").asFile
        f.parentFile.mkdirs()
        f.writeText(
            "package com.jayant.spendsense\n\n/** Generated by shared/build.gradle.kts. */\nobject BuildInfo {\n    const val VERSION_NAME: String = \"$appVersionName\"\n}\n",
        )
    }
}

